import contextlib
import importlib.util
import io
import unittest
from pathlib import Path
from tempfile import TemporaryDirectory
from unittest.mock import patch

_spec = importlib.util.spec_from_file_location(
    "githooks", Path(__file__).resolve().parents[1] / "scripts" / "githooks.py"
)
assert _spec and _spec.loader
githooks = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(githooks)

MESSAGES = [
    ("feat: add a feature", True),
    ("fix(px)!: drop a flag\n\nbody", True),
    ("# comment\n\nchore(core-deps): bump ansible", True),
    ("Merge branch 'main'", True),
    ("fixup! feat: x", True),
    ("update stuff", False),
    ("feat:missing space", False),
    ("feature: not a type", False),
    ("", False),
    ("feat: x\n\nCo-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>", False),
    ("feat: x\n\nco-authored-by: Codex <codex@users.noreply.github.com>", False),
    ("fix: x\n\n\U0001f916 Generated with [Claude Code](https://claude.com/claude-code)", False),
    ("fix: x\n\nGenerated by GitHub Copilot", False),
    ("feat: x\n\nCo-Authored-By: Jane Doe <jane@example.com>", True),
    ("docs: explain the Claude Code setup", True),
    ("feat: x\n# Co-Authored-By: Claude\n", True),
]


class CommitMessageTests(unittest.TestCase):
    def test_check_msg_and_ai(self):
        with TemporaryDirectory() as d, contextlib.redirect_stderr(io.StringIO()):
            file = Path(d) / "MSG"
            for message, ok in MESSAGES:
                with self.subTest(message=message):
                    file.write_text(message, encoding="utf-8")
                    result = githooks.check_msg(str(file)) == githooks.check_ai(str(file)) == 0
                    self.assertIs(result, ok)


class InstallTests(unittest.TestCase):
    def setUp(self):
        tmp = TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.dir = Path(tmp.name)
        hooks_dir = patch.object(githooks, "hooks_dir", lambda: self.dir)
        hooks_dir.start()
        self.addCleanup(hooks_dir.stop)
        quiet = contextlib.redirect_stdout(io.StringIO())
        quiet.__enter__()
        self.addCleanup(quiet.__exit__, None, None, None)

    def test_hooks_sharing_commit_msg_install_separately(self):
        hook = self.dir / "commit-msg"
        self.assertEqual(githooks.main(["install", "no-ai-signature"]), 0)
        self.assertEqual(githooks.installed(hook), {"no-ai-signature"})
        self.assertEqual(githooks.main(["install", "conventional-commits"]), 0)
        self.assertEqual(githooks.installed(hook), {"no-ai-signature", "conventional-commits"})
        self.assertIn("check-ai", hook.read_text())
        self.assertIn("check-msg", hook.read_text())
        self.assertEqual(githooks.main(["uninstall", "no-ai-signature"]), 0)
        self.assertEqual(githooks.installed(hook), {"conventional-commits"})
        self.assertNotIn("check-ai", hook.read_text())

    def test_install_uninstall_leave_foreign_hooks(self):
        (self.dir / "pre-push").write_text("#!/bin/sh\necho mine\n")
        self.assertEqual(githooks.main(["install"]), 1)
        self.assertTrue(githooks.is_ours(self.dir / "pre-commit"))
        self.assertTrue(githooks.is_ours(self.dir / "commit-msg"))
        self.assertFalse(githooks.is_ours(self.dir / "pre-push"))
        self.assertEqual(githooks.main(["uninstall", "pre-commit"]), 0)
        self.assertFalse((self.dir / "pre-commit").exists())
        self.assertEqual(githooks.main(["uninstall"]), 0)
        self.assertFalse((self.dir / "commit-msg").exists())
        self.assertEqual((self.dir / "pre-push").read_text(), "#!/bin/sh\necho mine\n")
        self.assertEqual(githooks.main(["install", "nope"]), 2)


if __name__ == "__main__":
    unittest.main()
